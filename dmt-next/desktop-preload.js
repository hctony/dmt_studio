const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('studio',{
  exportDiagnostics:()=>ipcRenderer.invoke('diagnostics:export'),
  networkStatus:()=>ipcRenderer.invoke('network:status'),
  configureNetwork:args=>ipcRenderer.invoke('network:configure',args),
  startServer:()=>ipcRenderer.invoke('network:start'),
  stopServer:()=>ipcRenderer.invoke('network:stop'),
  chooseNetworkRoot:()=>ipcRenderer.invoke('network:root'),
  copyAccessKey:name=>ipcRenderer.invoke('network:copy',name),
  cancelQueued:name=>ipcRenderer.invoke('network:cancel',name),
  connectClient:url=>ipcRenderer.invoke('network:client',url),
  measure:value=>ipcRenderer.invoke('measurement:enabled',value),
  exportMeasurements:()=>ipcRenderer.invoke('measurement:export'),
  workflow:(method,args)=>ipcRenderer.invoke('workflow:call',method,args),
  exportWorkflows:()=>ipcRenderer.invoke('workflow:export'),
  language:value=>ipcRenderer.invoke('ui:language',value),
  connection:()=>ipcRenderer.invoke('settings:connection-read'),
  saveConnection:values=>ipcRenderer.invoke('settings:connection-save',values),
  snapshot:()=>ipcRenderer.invoke('gui:snapshot'),
  stepImage:direction=>ipcRenderer.invoke('gui:image-step',direction),
  retryBackend:()=>ipcRenderer.invoke('backend:retry'),
  backendStatus:()=>ipcRenderer.invoke('backend:status'),
  action:args=>ipcRenderer.invoke('gui:action',args),
  reply:args=>ipcRenderer.invoke('gui:reply',args),
  onEvent:callback=>{const handler=(_e,value)=>callback(value);ipcRenderer.on('gui:event',handler);return()=>ipcRenderer.removeListener('gui:event',handler);},
  importSettings:()=>ipcRenderer.invoke('settings:import'),
  modelSettings:()=>ipcRenderer.invoke('settings:models'),
  applyModel:args=>ipcRenderer.invoke('settings:apply-model',args),
  settingsFolder:()=>ipcRenderer.invoke('settings:folder'),
  updateStatus:()=>ipcRenderer.invoke('update:status'),
  onUpdate:callback=>{const handler=(_e,value)=>callback(value);ipcRenderer.on('update:state',handler);return()=>ipcRenderer.removeListener('update:state',handler);},
  checkUpdate:()=>ipcRenderer.invoke('update:check'),
  installUpdate:()=>ipcRenderer.invoke('update:install')
});
